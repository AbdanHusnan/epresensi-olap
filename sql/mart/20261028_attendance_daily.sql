-- Contract ATTENDANCE_DAILY_V1. Run with psql -v ON_ERROR_STOP=1.
-- One-time, transactional migration; existing objects cause an error, never DROP.
BEGIN;
SET LOCAL lock_timeout = '5s';
SELECT pg_advisory_xact_lock(hashtext('attendance_daily_v1_schema'));
CREATE EXTENSION IF NOT EXISTS btree_gist;
CREATE SCHEMA mart_kehadiran;
CREATE SCHEMA serving;
CREATE SCHEMA IF NOT EXISTS etl_control;
CREATE TABLE mart_kehadiran.dim_calendar (
 tanggal date PRIMARY KEY,
 tanggal_key integer GENERATED ALWAYS AS
 (extract(year from tanggal)::integer*10000+extract(month from tanggal)::integer*100+extract(day from tanggal)::integer) STORED UNIQUE
);
CREATE TABLE mart_kehadiran.dim_pegawai (
 pegawai_key bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 pegawai_id_sumber integer,
 nama text,
 valid_from date NOT NULL,
 valid_to date,
 CHECK (valid_to IS NULL OR valid_to > valid_from),
 CHECK ((pegawai_key=0 AND pegawai_id_sumber IS NULL) OR (pegawai_key>0 AND pegawai_id_sumber IS NOT NULL)),
 EXCLUDE USING gist (pegawai_id_sumber WITH =, daterange(valid_from,valid_to,'[)') WITH &&)
);
CREATE TABLE mart_kehadiran.dim_departemen (
 departemen_key bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 departemen_id_sumber integer,
 nama text,
 valid_from date NOT NULL,
 valid_to date,
 CHECK (valid_to IS NULL OR valid_to > valid_from),
 CHECK ((departemen_key=0 AND departemen_id_sumber IS NULL) OR (departemen_key>0 AND departemen_id_sumber IS NOT NULL)),
 EXCLUDE USING gist (departemen_id_sumber WITH =, daterange(valid_from,valid_to,'[)') WITH &&)
);
INSERT INTO mart_kehadiran.dim_departemen(departemen_key,departemen_id_sumber,nama,valid_from)
VALUES (0,NULL,'Belum terpetakan','0001-01-01');
CREATE TABLE etl_control.mart_batch (
 batch_id text PRIMARY KEY,
 contract_version text NOT NULL CHECK(contract_version='ATTENDANCE_DAILY_V1'),
 status text NOT NULL CHECK(status IN ('READY','APPLIED')),
 created_at timestamptz NOT NULL DEFAULT current_timestamp,
 applied_at timestamptz,
 CHECK ((status='APPLIED')=(applied_at IS NOT NULL))
);
CREATE TABLE mart_kehadiran.fact_kehadiran_daily (
 pegawai_id_sumber integer NOT NULL,
 tanggal date NOT NULL REFERENCES mart_kehadiran.dim_calendar(tanggal),
 tanggal_key integer GENERATED ALWAYS AS
 (extract(year from tanggal)::integer*10000+extract(month from tanggal)::integer*100+extract(day from tanggal)::integer) STORED,
 pegawai_key bigint NOT NULL REFERENCES mart_kehadiran.dim_pegawai,
 departemen_key bigint NOT NULL REFERENCES mart_kehadiran.dim_departemen,
 departemen_id_sumber integer,
 is_employee_active boolean,
 population_basis text CHECK(population_basis IN ('AS_OF_DATE_SNAPSHOT','EXTRACTION_SNAPSHOT')),
 has_masuk boolean NOT NULL,
 has_pulang boolean NOT NULL,
 checkin_event_count integer NOT NULL CHECK(checkin_event_count>=0),
 checkout_event_count integer NOT NULL CHECK(checkout_event_count>=0),
 first_checkin_at timestamp,
 last_checkout_at timestamp,
 has_manual_event boolean NOT NULL,
 has_valid_leave boolean NOT NULL,
 has_full_day_leave boolean NOT NULL,
 has_partial_day_leave boolean NOT NULL,
 has_excused_checkin boolean NOT NULL,
 has_excused_checkout boolean NOT NULL,
 active_employee_days smallint NOT NULL CHECK (active_employee_days = CASE WHEN is_employee_active THEN 1 ELSE 0 END),
 checkin_days smallint NOT NULL CHECK (checkin_days = CASE WHEN is_employee_active AND has_masuk THEN 1 ELSE 0 END),
 checkout_days smallint NOT NULL CHECK (checkout_days = CASE WHEN is_employee_active AND has_pulang THEN 1 ELSE 0 END),
 no_checkin_days smallint NOT NULL CHECK (no_checkin_days = CASE WHEN is_employee_active AND NOT has_excused_checkin AND NOT has_masuk THEN 1 ELSE 0 END),
 no_checkout_days smallint NOT NULL CHECK (no_checkout_days = CASE WHEN is_employee_active AND NOT has_excused_checkout AND NOT has_pulang THEN 1 ELSE 0 END),
 leave_days smallint NOT NULL CHECK (leave_days = CASE WHEN is_employee_active AND has_valid_leave THEN 1 ELSE 0 END),
 required_checkin_days smallint NOT NULL CHECK (required_checkin_days = CASE WHEN is_employee_active AND NOT has_excused_checkin THEN 1 ELSE 0 END),
 required_checkout_days smallint NOT NULL CHECK (required_checkout_days = CASE WHEN is_employee_active AND NOT has_excused_checkout THEN 1 ELSE 0 END),
 excused_checkin_days smallint NOT NULL CHECK (excused_checkin_days = CASE WHEN is_employee_active AND has_excused_checkin THEN 1 ELSE 0 END),
 excused_checkout_days smallint NOT NULL CHECK (excused_checkout_days = CASE WHEN is_employee_active AND has_excused_checkout THEN 1 ELSE 0 END),
 required_checkin_present_days smallint NOT NULL CHECK (required_checkin_present_days = CASE WHEN is_employee_active AND NOT has_excused_checkin AND has_masuk THEN 1 ELSE 0 END),
 required_checkout_present_days smallint NOT NULL CHECK (required_checkout_present_days = CASE WHEN is_employee_active AND NOT has_excused_checkout AND has_pulang THEN 1 ELSE 0 END),
 perlu_review boolean NOT NULL,
 alasan_review text,
 is_date_final boolean NOT NULL DEFAULT false,
 date_assignment_policy text NOT NULL,
 source_snapshot_at timestamptz NOT NULL,
 source_batch_id text NOT NULL REFERENCES etl_control.mart_batch(batch_id),
 contract_version text NOT NULL CHECK(contract_version='ATTENDANCE_DAILY_V1'),
 mart_loaded_at timestamptz NOT NULL DEFAULT current_timestamp,
 PRIMARY KEY(pegawai_id_sumber,tanggal),
 CHECK(has_masuk=(checkin_event_count>0)),
 CHECK(has_pulang=(checkout_event_count>0)),
 CHECK(has_masuk=(first_checkin_at IS NOT NULL)),
 CHECK(has_pulang=(last_checkout_at IS NOT NULL)),
 CHECK(is_employee_active IS NULL OR population_basis IS NOT NULL),
 CHECK(NOT(has_full_day_leave OR has_partial_day_leave OR has_excused_checkin OR has_excused_checkout) OR has_valid_leave),
 CHECK(NOT has_full_day_leave OR (has_excused_checkin AND has_excused_checkout))
);
CREATE INDEX fact_date_department_idx ON mart_kehadiran.fact_kehadiran_daily(tanggal,departemen_key);
CREATE INDEX fact_department_date_idx ON mart_kehadiran.fact_kehadiran_daily(departemen_key,tanggal);
CREATE TABLE serving.attendance_date_state (
 tanggal date PRIMARY KEY REFERENCES mart_kehadiran.dim_calendar(tanggal),
 population_complete boolean NOT NULL DEFAULT false,
 curated_delivery_complete boolean NOT NULL DEFAULT false,
 is_closed boolean NOT NULL DEFAULT false,
 published_batch_id text NOT NULL REFERENCES etl_control.mart_batch(batch_id),
 updated_at timestamptz NOT NULL DEFAULT current_timestamp,
 CHECK(NOT is_closed OR (population_complete AND curated_delivery_complete))
);
CREATE TABLE serving.agg_kehadiran_departemen_harian (
 tanggal date NOT NULL REFERENCES mart_kehadiran.dim_calendar(tanggal),
 tanggal_key integer GENERATED ALWAYS AS
 (extract(year from tanggal)::integer*10000+extract(month from tanggal)::integer*100+extract(day from tanggal)::integer) STORED,
 departemen_key bigint NOT NULL REFERENCES mart_kehadiran.dim_departemen,
 active_employee_days bigint NOT NULL CHECK(active_employee_days>=0),
 checkin_days bigint NOT NULL CHECK(checkin_days>=0),
 checkout_days bigint NOT NULL CHECK(checkout_days>=0),
 no_checkin_days bigint NOT NULL CHECK(no_checkin_days>=0),
 no_checkout_days bigint NOT NULL CHECK(no_checkout_days>=0),
 leave_days bigint NOT NULL CHECK(leave_days>=0),
 required_checkin_days bigint NOT NULL CHECK(required_checkin_days>=0),
 required_checkout_days bigint NOT NULL CHECK(required_checkout_days>=0),
 excused_checkin_days bigint NOT NULL CHECK(excused_checkin_days>=0),
 excused_checkout_days bigint NOT NULL CHECK(excused_checkout_days>=0),
 required_checkin_present_days bigint NOT NULL CHECK(required_checkin_present_days>=0),
 required_checkout_present_days bigint NOT NULL CHECK(required_checkout_present_days>=0),
 fact_rows bigint NOT NULL CHECK(fact_rows>0),
 review_rows bigint NOT NULL CHECK(review_rows BETWEEN 0 AND fact_rows),
 nonfinal_rows bigint NOT NULL CHECK(nonfinal_rows BETWEEN 0 AND fact_rows),
 is_provisional boolean GENERATED ALWAYS AS (review_rows>0 OR nonfinal_rows>0) STORED,
 serving_batch_id text NOT NULL REFERENCES etl_control.mart_batch(batch_id),
 refreshed_at timestamptz NOT NULL DEFAULT current_timestamp,
 PRIMARY KEY(tanggal,departemen_key),
 UNIQUE(tanggal_key,departemen_key),
 CHECK(active_employee_days<=fact_rows),
 CHECK(active_employee_days=required_checkin_days+excused_checkin_days),
 CHECK(active_employee_days=required_checkout_days+excused_checkout_days),
 CHECK(required_checkin_days=required_checkin_present_days+no_checkin_days),
 CHECK(required_checkout_days=required_checkout_present_days+no_checkout_days),
 CHECK(leave_days<=active_employee_days),
 CHECK(checkin_days BETWEEN required_checkin_present_days AND active_employee_days),
 CHECK(checkout_days BETWEEN required_checkout_present_days AND active_employee_days)
);
CREATE INDEX agg_department_date_idx ON serving.agg_kehadiran_departemen_harian(departemen_key,tanggal);
CREATE VIEW serving.v_kehadiran_departemen_harian AS
SELECT a.tanggal,a.tanggal_key,a.departemen_key,d.departemen_id_sumber,d.nama AS nama_departemen,
 a.active_employee_days,
 a.checkin_days,
 a.checkout_days,
 a.no_checkin_days,
 a.no_checkout_days,
 a.leave_days,
 a.required_checkin_days,
 a.required_checkout_days,
 a.excused_checkin_days,
 a.excused_checkout_days,
 a.required_checkin_present_days,
 a.required_checkout_present_days,a.fact_rows,a.review_rows,a.nonfinal_rows,
 100.0*a.checkin_days/NULLIF(a.active_employee_days,0) AS checkin_rate,
 100.0*a.checkout_days/NULLIF(a.active_employee_days,0) AS checkout_rate,
 100.0*a.required_checkin_present_days/NULLIF(a.required_checkin_days,0) AS required_checkin_rate,
 100.0*a.required_checkout_present_days/NULLIF(a.required_checkout_days,0) AS required_checkout_rate,
 COALESCE(s.population_complete AND s.curated_delivery_complete,false) AS is_data_complete,
 (a.is_provisional OR NOT COALESCE(s.is_closed AND s.population_complete AND s.curated_delivery_complete,false)) AS is_provisional,
 a.serving_batch_id,a.refreshed_at
FROM serving.agg_kehadiran_departemen_harian a
JOIN mart_kehadiran.dim_departemen d USING(departemen_key)
LEFT JOIN serving.attendance_date_state s USING(tanggal);
CREATE VIEW serving.v_kehadiran_instansi_harian AS
WITH a AS (
 SELECT tanggal,tanggal_key,
 SUM(active_employee_days) AS active_employee_days,
 SUM(checkin_days) AS checkin_days,
 SUM(checkout_days) AS checkout_days,
 SUM(no_checkin_days) AS no_checkin_days,
 SUM(no_checkout_days) AS no_checkout_days,
 SUM(leave_days) AS leave_days,
 SUM(required_checkin_days) AS required_checkin_days,
 SUM(required_checkout_days) AS required_checkout_days,
 SUM(excused_checkin_days) AS excused_checkin_days,
 SUM(excused_checkout_days) AS excused_checkout_days,
 SUM(required_checkin_present_days) AS required_checkin_present_days,
 SUM(required_checkout_present_days) AS required_checkout_present_days,
 SUM(fact_rows) AS fact_rows,SUM(review_rows) AS review_rows,SUM(nonfinal_rows) AS nonfinal_rows,
 bool_and(is_data_complete) AS is_data_complete,bool_or(is_provisional) AS is_provisional,
 MIN(refreshed_at) AS oldest_partition_refreshed_at,MAX(refreshed_at) AS latest_partition_refreshed_at
 FROM serving.v_kehadiran_departemen_harian GROUP BY tanggal,tanggal_key
)
SELECT a.*,
100.0*a.checkin_days/NULLIF(a.active_employee_days,0) AS checkin_rate,
 100.0*a.checkout_days/NULLIF(a.active_employee_days,0) AS checkout_rate,
 100.0*a.required_checkin_present_days/NULLIF(a.required_checkin_days,0) AS required_checkin_rate,
 100.0*a.required_checkout_present_days/NULLIF(a.required_checkout_days,0) AS required_checkout_rate FROM a;
CREATE VIEW serving.v_departemen_filter AS
SELECT DISTINCT ON (departemen_id_sumber) departemen_id_sumber,nama AS nama_departemen
FROM mart_kehadiran.dim_departemen
ORDER BY departemen_id_sumber,valid_from DESC,departemen_key DESC;
COMMENT ON TABLE mart_kehadiran.fact_kehadiran_daily IS 'ATTENDANCE_DAILY_V1: all shifts, employee/reporting-date; copied curated measures. Not an event fact.';
COMMENT ON TABLE serving.agg_kehadiran_departemen_harian IS 'SUM daily fact measures by date/department. No ALL row. Provisional also requires date_state checks via serving views.';
COMMIT;
